"""Writes tickets/status_names.py from the status list; run by `make generate`."""
from pathlib import Path

from tickets.status import STATUSES

TARGET = Path(__file__).resolve().parent.parent / "tickets" / "status_names.py"


def main():
    lines = ["# Generated by scripts/gen_status_names.py from tickets/status.py — do not edit.", "", "STATUS_NAMES = {"]
    lines += [f'    "{status}": "{status.capitalize()}",' for status in STATUSES]
    lines += ["}", ""]
    TARGET.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
